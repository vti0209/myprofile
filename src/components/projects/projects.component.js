export function ProjectsComponent(projects, lang) {
  const isVi = lang === 'vi';
  
  const subtitleText = isVi ? "Dự án" : "Portfolio";
  const descText = isVi 
    ? "Dưới đây là một số dự án đã thực hiện trong quá trình học tập và tự học về phát triển website và di động." 
    : "Below are some projects implemented during my studies and self-learning in web and mobile development.";

  const filterAll = isVi ? "Tất cả" : "All";
  const filterDesign = isVi ? "Thiết kế" : "Design";
  const filterWeb = isVi ? "Website" : "Website";
  const filterGroup = isVi ? "Nhóm" : "Group";

  const ctaTitle = isVi ? "Bạn muốn cộng tác cùng tôi?" : "Want to collaborate with me?";
  const ctaDesc = isVi 
    ? "Rất vui được cùng bạn tạo ra những sản phẩm sáng tạo và hữu ích." 
    : "Very glad to create creative and useful products with you.";
  const ctaBtn = isVi ? "Liên hệ hợp tác" : "Contact for Collaboration";

  const cardsHTML = projects.map(p => {
    const title = p.getTitle(lang);
    const categoryName = p.getCategory(lang);
    const desc = p.getDescription(lang);
    
    // Tech badges
    const techHTML = p.tech.map(t => `<span class="tech-badge">${t}</span>`).join('');
    
    // Actions button
    let thirdAction = '';
    if (p.demo && p.demo !== '#') {
      if (p.demo.includes('figma.com')) {
        thirdAction = `<a href="${p.demo}" target="_blank" title="Figma"><i class="bi bi-pencil-square"></i></a>`;
      } else {
        thirdAction = `<a href="${p.demo}" target="_blank" title="Demo"><i class="bi bi-display"></i></a>`;
      }
    } else if (p.github && p.github !== '#') {
      thirdAction = `<a href="${p.github}" target="_blank" title="GitHub"><i class="bi bi-github"></i></a>`;
    }

    return `
      <div class="col-lg-4 col-md-6 portfolio-item isotope-item ${p.category}">
        <div class="portfolio-card">
          <div class="portfolio-image-container">
            <img src="${p.image}" alt="${title}" class="img-fluid" loading="lazy">
            <div class="portfolio-overlay">
              <div class="portfolio-actions">
                <a href="${p.image}" class="glightbox portfolio-link" title="Zoom"><i class="bi bi-zoom-in"></i></a>
                <a href="#" class="portfolio-details" 
                   data-bs-toggle="modal" 
                   data-bs-target="#projectModal" 
                   data-details-id="${p.hasRichDetails ? `details-${p.id}` : ''}"
                   data-title="${title}" 
                   data-description="${desc}"
                   data-tech="${p.tech.join(', ')}"
                   data-github="${p.github}"
                   data-demo="${p.demo}"
                   data-image="${p.image}"
                   title="${isVi ? 'Chi tiết' : 'Details'}">
                  <i class="bi bi-info-circle"></i>
                </a>
                ${thirdAction}
              </div>
            </div>
          </div>
          <div class="portfolio-content">
            <span class="project-category" data-vi="${p.categoryVi}" data-en="${p.categoryEn}">${categoryName}</span>
            <h4>${title}</h4>
            <p class="project-description" data-vi="${p.descriptionVi}" data-en="${p.descriptionEn}">${desc}</p>
            <div class="project-tech-stack">
              ${techHTML}
            </div>
            <div class="project-footer">
              <span class="project-year">${p.year}</span>
            </div>
          </div>
        </div>
      </div>
    `;
  }).join('');

  return `
    <!-- Section Title -->
    <div class="container section-title" data-aos="fade-up">
      <span class="subtitle" data-vi="Dự án" data-en="Portfolio">${subtitleText}</span>
      <p data-vi="${descText}" data-en="${descText}">${descText}</p>
    </div><!-- End Section Title -->

    <div class="container" data-aos="fade-up" data-aos-delay="100">

      <div class="isotope-layout" data-default-filter="*" data-layout="masonry" data-sort="original-order">
        <ul class="portfolio-filters isotope-filters" data-aos="fade-up" data-aos-delay="200">
          <li data-filter="*" class="filter-active" data-vi="Tất cả" data-en="All">${filterAll}</li>
          <li data-filter=".filter-design" data-vi="Thiết kế" data-en="Design">${filterDesign}</li>
          <li data-filter=".filter-web" data-vi="Website" data-en="Website">${filterWeb}</li>
          <li data-filter=".filter-group" data-vi="Nhóm" data-en="Group">${filterGroup}</li>
        </ul>

        <div class="row gy-3 isotope-container" data-aos="fade-up" data-aos-delay="300">
          ${cardsHTML}
        </div>

        <div class="portfolio-pagination" id="portfolio-pagination">
          <!-- Pagination will be generated by JS -->
        </div>
      </div>

      <div class="portfolio-bottom" data-aos="fade-up" data-aos-delay="400">
        <div class="row align-items-center">
          <div class="col-lg-8">
            <h3 data-vi="Bạn muốn cộng tác cùng tôi?" data-en="Want to collaborate with me?">${ctaTitle}</h3>
            <p data-vi="Rất vui được cùng bạn tạo ra những sản phẩm sáng tạo và hữu ích." data-en="Very glad to create creative and useful products with you.">${ctaDesc}</p>
          </div>
          <div class="col-lg-4 text-lg-end">
            <a href="#contact" class="btn btn-accent" data-vi="Liên hệ hợp tác" data-en="Contact for Collaboration">${ctaBtn}</a>
          </div>
        </div>
      </div>

    </div>
  `;
}
